// Дедуплицирующая обёртка: ручной список выше может содержать опечатки-дубликаты
// (Подольск/Шахты/Магнитогорск встречаются по 2 раза в Росстат-выгрузке если
// город есть в нескольких регионах). Set-конверсия защищает от падения UI на
// duplicate React-keys в выпадашке.
const CITIES_DEDUPED: readonly string[] = Array.from(new Set(CITIES_RU));

export function searchCities(query: string, limit = 20): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return CITIES_DEDUPED.slice(0, limit);
  const startsWith: string[] = [];
  const contains: string[] = [];
  for (const city of CITIES_DEDUPED) {
    const lower = city.toLowerCase();
    if (lower.startsWith(q)) startsWith.push(city);
    else if (lower.includes(q)) contains.push(city);
    if (startsWith.length >= limit) break;
  }
  return [...startsWith, ...contains].slice(0, limit);
}

export function isKnownCity(name: string): boolean {
  const target = name.trim().toLowerCase();
  if (!target) return false;
  return CITIES_DEDUPED.some((c) => c.toLowerCase() === target);
}
